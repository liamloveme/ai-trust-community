#!/usr/bin/env python3
"""Chromium end-to-end interactive batch moderation checks on single-file offline preview."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
ROOT=Path(__file__).resolve().parents[1]
HTML=(ROOT/'AI交易守望站-独立HTML预览.html').read_text(encoding='utf-8')
checks=[];errors=[]
def ok(cond,name):
 checks.append((name,bool(cond))); print(('PASS' if cond else 'FAIL'),name,flush=True)
def login(page,email):
 page.locator('#accountButton').click()
 page.locator('#authForm [name=email]').fill(email)
 page.locator('#authForm [name=password]').fill('Demo123456!')
 page.locator('#authForm button[type=submit]').click()
 page.locator('#authForm').wait_for(state='detached')
def tab(page,name):
 page.locator(f'.admin-tabs [data-tab={name}]').click()
 page.locator(f'.admin-tabs [data-tab={name}].active').wait_for()
 page.locator('#adminPanel .admin-empty, #adminPanel .batch-toolbar, #adminPanel .user-card, #adminPanel .admin-item, #adminPanel .audit-record').first.wait_for()
def batch(page,button_text,note='已人工逐条检查内容和证据并确认符合管理规则',approve=False):
 page.locator('#batchSelectAll').check()
 page.locator('#batchCount').wait_for()
 page.locator('#adminPanel [data-action=batch-start]').filter(has_text=button_text).click()
 page.locator('#batchForm').wait_for()
 page.locator('#batchReason').fill(note)
 if approve:
  ok(page.locator('#batchForm [name=reviewedEvidence]').count()==1, 'batch publish requires evidence attestation')
  page.locator('#batchForm [name=reviewedEvidence]').check()
 page.locator('#batchForm button[type=submit]').click()
 page.locator('.batch-result').wait_for()
with sync_playwright() as pw:
 browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 p=browser.new_page(viewport={'width':1440,'height':900})
 p.set_default_timeout(10000)
 p.on('pageerror',lambda e:errors.append(str(e)))
 p.set_content(HTML,wait_until='load')
 p.locator('#postList').wait_for()
 login(p,'root@demo.test')
 p.locator('.super-entry').click()
 tab(p,'posts')
 ok(p.locator('#adminPanel [data-batch-id="108"]').count()==1,'risk-exposure pending item has batch checkbox')
 ok(p.locator('#batchSelectAll').count()==1,'pending posts support select all')
 batch(p,'批量批准',approve=True)
 ok('成功 1 条' in p.locator('.batch-result').inner_text(),'risk-exposure post batch approval succeeds after explicit review')
 ok(p.locator('[data-tab=posts].active').count()==1,'batch operation remains in review queue')
 tab(p,'published')
 ok(p.locator('#batchSelectAll').count()==1,'published posts support select all')
 p.locator('#adminPanel [data-batch-id="108"]').check()
 p.locator('#adminPanel [data-action=batch-start]').filter(has_text='批量下架').click()
 p.locator('#batchReason').fill('已核对请求和证据，按管理员决议下架此帖子')
 p.locator('#batchForm button[type=submit]').click()
 p.locator('.batch-result').wait_for()
 ok('成功 1 条' in p.locator('.batch-result').inner_text(),'batch removal succeeds on selected post')
 tab(p,'reports');ok(p.locator('#batchSelectAll').count()==1,'reports tab supports bulk selection')
 batch(p,'批量标记已处理')
 ok('成功 1 条' in p.locator('.batch-result').inner_text(),'reports batch resolved')
 tab(p,'appeals');ok(p.locator('#batchSelectAll').count()==1,'appeals support bulk selection')
 batch(p,'批量受理申诉')
 ok('成功 1 条' in p.locator('.batch-result').inner_text(),'appeals batch accepted')
 tab(p,'users');ok(p.locator('#batchSelectAll').count()==1,'member management supports bulk selection')
 batch(p,'批量禁言24小时')
 ok('成功' in p.locator('.batch-result').inner_text(),'bulk mute executed with per-user results')
 tab(p,'sections');ok(p.locator('#batchSelectAll').count()==1,'sections support bulk selection')
 batch(p,'批量停用')
 ok('成功' in p.locator('.batch-result').inner_text(),'bulk disable section executed')
 tab(p,'audit')
 ok('batch_id' in p.locator('#adminPanel').inner_text() or '批次' in p.locator('#adminPanel').inner_text(),'audit includes batch correlation info')
 p.locator('#accountButton').click()
 login(p,'mod@demo.test')
 p.locator('.admin-entry').click()
 tab(p,'published')
 ok(p.locator('#batchSelectAll').count()==1,'moderator receives batch tools in authorized tabs')
 ok(p.locator('#adminPanel .admin-item').filter(has_text='管理员公告').count()==0,'moderator list excludes moderator-authored posts')
 for w in (320,390,768,1024,1440):
  p.set_viewport_size({'width':w,'height':900})
  p.wait_for_timeout(100)
  ok(p.evaluate('document.documentElement.scrollWidth<=window.innerWidth+2'),f'batch dashboard fits {w}px')
 ok(len(errors)==0,'no uncaught JavaScript exceptions')
 p.set_viewport_size({'width':1440,'height':900})
 p.screenshot(path=str(ROOT/'tests/v31-batch-screenshot.png'),full_page=False)
 browser.close()
result={'tests':[{'name':n,'passed':v} for n,v in checks],'errors':errors,'passed':sum(v for _,v in checks),'total':len(checks)}
(ROOT/'tests/v31-batch-report.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
print('SUMMARY',result['passed'],'/',result['total'],'JSERR',len(errors))
if result['passed']!=result['total'] or errors:raise SystemExit(1)
