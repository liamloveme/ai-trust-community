def check(expr,name):
 results.append({'name':name,'pass':bool(expr)});print(('PASS' if expr else 'FAIL'),name,flush=True)
def login(page,email,password):
 page.locator('#accountButton').click();page.locator('#authForm [name=email]').fill(email);page.locator('#authForm [name=password]').fill(password);page.locator('#authForm button[type=submit]').click();page.wait_for_timeout(220)
