 browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 p=browser.new_page(viewport={'width':1280,'height':900});p.on('pageerror',lambda e:errors.append(str(e)));p.set_content(html,wait_until='load');p.wait_for_timeout(280)
 p.locator('#accountButton').click();check(p.locator('[data-action=forgot-password]').count()==1,'forgot password link in unified login')
 p.locator('[data-action=forgot-password]').click();check(p.locator('#forgotPasswordForm').count()==1,'forgot password form')
 p.locator('#forgotPasswordForm [name=email]').fill('member@demo.test');p.locator('#forgotPasswordForm button[type=submit]').click();p.wait_for_timeout(200)
 check(p.locator('[data-action=preview-reset]').count()==1,'offline email simulation available')
 p.locator('[data-action=preview-reset]').click();check(p.locator('#resetPasswordForm').count()==1,'email reset link opens set-password form')
 p.locator('#resetPasswordForm [name=newPassword]').fill('NewMemberPassword345!');p.locator('#resetPasswordForm [name=confirmPassword]').fill('NewMemberPassword345!');p.locator('#resetPasswordForm button[type=submit]').click();p.wait_for_timeout(240)
 check(p.locator('#authForm').count()==1,'reset returns to login')
